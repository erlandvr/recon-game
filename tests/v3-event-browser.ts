import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
const require = createRequire(import.meta.url), {chromium} = require(`${process.env.PLAYWRIGHT_MODULE_DIR}/playwright`);
const browser = await chromium.launch(), errors: string[] = [];
const dir = 'test-results/v3-event'; await mkdir(dir, {recursive:true});
try {
  const p = await browser.newPage({viewport:{width:1280,height:720}});
  p.on('pageerror',(e:Error)=>errors.push(e.message));
  p.on('request',(r:any)=>{if(/supabase\.co/.test(r.url())) errors.push('Unexpected backend request');});
  const date = new Date('2026-10-20T10:00:00Z'); await p.clock.install({time:date}); await p.clock.pauseAt(date);
  await p.goto(process.env.GAME_URL ?? 'http://127.0.0.1:5175/recon-game/');
  await p.screenshot({path:`${dir}/entry.png`});
  assert.equal(await p.title(), 'Recon — Active Animation');
  assert.equal(await p.locator('.mode-options').count(), 0);
  assert.equal(await p.getByRole('button', {name: /choose|scoreboard/i}).count(), 0);
  const start = p.getByRole('button',{name:'Start experience',exact:true});
  assert.equal(await start.evaluate((e:Element)=>e===document.activeElement),true);
  const opening = p.locator('.v3-opening');
  assert.equal(await opening.getByRole('button').count(),1);
  assert.equal(await p.locator('[data-demo-time],.v3-attract').count(),0);
  assert.equal(await p.locator('.v3-main').isVisible(),false);
  assert.equal(await p.locator('.v3-header').isVisible(),false);
  assert.match(await opening.innerText(),/Recon — Active Animation/);
  assert.match(await opening.innerText(),/Experience the Benefit of Recon/);
  assert.match(await opening.innerText(),/1,200 credits/);
  assert.match(await opening.innerText(),/P1 fires/);
  await p.keyboard.press('Tab'); assert.equal(await start.evaluate((e:Element)=>e===document.activeElement),true);
  await p.clock.runFor(60000);
  assert.equal(await p.locator('.v3-game').getAttribute('data-time'),'0');
  assert.equal(await p.locator('.v3-game').getAttribute('data-cash'),'90');
  for(const [width,height] of [[1024,768],[1280,720],[1440,900],[1920,1080]]) {
    await p.setViewportSize({width,height});
    const bounds=await p.locator('.v3-opening').evaluate((e:Element)=>{const r=e.getBoundingClientRect();return {x:r.x,y:r.y,right:r.right,bottom:r.bottom,scroll:e.scrollHeight>e.clientHeight};});
    assert.ok(bounds.x>=0&&bounds.y>=0&&bounds.right<=width&&bounds.bottom<=height&&!bounds.scroll,JSON.stringify(bounds));
    await p.screenshot({path:`${dir}/opening-${width}.png`});
  }
  await start.click(); assert.equal(await opening.count(),0);
  assert.equal(await p.locator('.v3-main').isVisible(),true);
  await p.clock.runFor(3000); assert.equal(await p.locator('.v3-game').getAttribute('data-time'),'0');
  await p.clock.runFor(1000); assert.equal(await p.locator('.v3-game').getAttribute('data-time'),'1');
  assert.deepEqual(await p.getByRole('navigation', {name: 'Experience controls'}).getByRole('button').allTextContents(), ['Restart']);
  await p.emulateMedia({reducedMotion: 'reduce'});
  await p.waitForFunction(() => document.querySelector('.v3-game')?.getAttribute('data-reduced') === 'true');
  await p.emulateMedia({reducedMotion: 'no-preference'});
  await p.waitForFunction(() => document.querySelector('.v3-game')?.getAttribute('data-reduced') === 'false');
  await p.setViewportSize({width:1280,height:720});
  await p.screenshot({path:`${dir}/restart-only.png`});
  await p.getByRole('button',{name:'Restart',exact:true}).click();
  const held = await p.locator('.v3-game').getAttribute('data-time');
  await p.clock.runFor(5000);
  assert.equal(await p.locator('.v3-game').getAttribute('data-time'), held);
  await p.getByRole('button', {name: 'Keep this workshop', exact: true}).click();
  await p.clock.runFor(1000);
  assert.equal(Number(await p.locator('.v3-game').getAttribute('data-time')), Number(held) + 1);
  await p.getByRole('button', {name: 'Restart', exact: true}).click();
  await p.keyboard.press('Escape');
  assert.equal(await p.locator('.v3-game').getAttribute('data-status'), 'running');
  await p.getByRole('button', {name: 'Restart', exact: true}).click();
  assert.equal(await p.getByRole('button', {name: /choose|mode/i}).count(), 0);
  await p.getByRole('button',{name:'Start fresh',exact:true}).click();
  assert.equal(await p.locator('.v3-game').getAttribute('data-cash'),'90');
  assert.equal(await opening.getByRole('button').count(),1);
  assert.equal(await p.locator('.v3-game').getAttribute('data-time'),'0');
  assert.deepEqual(errors,[]); console.log('Explanation-only opening, single focused Start experience button, held clock, four desktop sizes, countdown and fresh replay pass.');
} finally {await browser.close();}
